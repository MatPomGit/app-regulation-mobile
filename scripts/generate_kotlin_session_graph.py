#!/usr/bin/env python3
"""Generate the Kotlin session graph from the authoritative JSON contract.

Run from the repository root:
    python scripts/generate_kotlin_session_graph.py
    python scripts/generate_kotlin_session_graph.py --check

Only graph structure is translated. Eligibility, qualification, persistence
and scientific recovery decisions remain separate implementation boundaries.
"""

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "config/core_session_state_machine.example.json"
OUTPUT = (
    ROOT / "android/app/src/main/java"
    "/pl/edu/prz/arcadhd/session/SessionGraph.kt"
)


def generate(source: bytes) -> str:
    """Render deterministic Kotlin declarations and the source SHA-256."""
    contract = json.loads(source)
    source_hash = hashlib.sha256(source).hexdigest()
    states = contract["states"]
    lines = [
        "// Generated by scripts/generate_kotlin_session_graph.py. "
        "Do not edit.",
        "package pl.edu.prz.arcadhd.session",
        "",
        "enum class SessionState {",
    ]
    lines.extend(f"    {state}," for state in states)
    lines += ["}", "", "object SessionGraph {"]
    lines += [
        f'    const val SCHEMA_VERSION = "{contract["schema_version"]}"',
        f'    const val SOURCE_SHA256 = "{source_hash}"',
        f'    val initial = SessionState.{contract["initial_state"]}',
        "    val terminal = setOf(",
    ]
    lines.extend(
        f"        SessionState.{state},"
        for state in contract["terminal_states"]
    )
    lines += ["    )", "    val priority = listOf("]
    lines.extend(
        f'        "{priority}",' for priority in contract["global_priority"]
    )
    lines += [
        "    )",
        "    // A null destination is the explicit stored resume target.",
        "    val transitions: Map<SessionState, Map<String, SessionState?>> "
        "= mapOf(",
    ]
    for state, definition in states.items():
        edges = definition["transitions"]
        if not edges:
            lines.append(f"        SessionState.{state} to emptyMap(),")
            continue
        lines.append(f"        SessionState.{state} to mapOf(")
        for event, target in edges.items():
            value = (
                "null" if target == "$RESUME_TARGET"
                else f"SessionState.{target}"
            )
            lines.append(f'            "{event}" to {value},')
        lines.append("        ),")
    lines += ["    )", "}", ""]
    return "\n".join(lines)


def main() -> int:
    """Write the generated graph or fail when the committed graph is stale."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = generate(SOURCE.read_bytes())
    if args.check:
        actual = (
            OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else None
        )
        if actual != expected:
            print("Kotlin graph is stale; run this script without --check.")
            return 1
        print("Kotlin session graph matches the authoritative JSON contract.")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(expected, encoding="utf-8")
    print(f"Generated {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
