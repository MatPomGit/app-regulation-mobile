package pl.edu.prz.arcadhd.core

import pl.edu.prz.arcadhd.BuildConfig

/** Compile-time research application variant and its optional capabilities. */
data class StudyVariant(
    val paperId: String,
    val label: String,
    val facialGazeEnabled: Boolean,
    val bilateralAudioEnabled: Boolean,
    val embodiedArEnabled: Boolean,
    val eegEnabled: Boolean,
) {
    /** True only for the core Paper 1 build with no companion module enabled. */
    val isCoreOnly: Boolean
        get() = !facialGazeEnabled &&
            !bilateralAudioEnabled &&
            !embodiedArEnabled &&
            !eegEnabled

    companion object {
        /** Resolve the immutable feature set generated by the selected Gradle flavor. */
        fun current(): StudyVariant = StudyVariant(
            paperId = BuildConfig.PAPER_ID,
            label = when (BuildConfig.PAPER_ID) {
                "P1" -> "Core closed-loop"
                "P2" -> "Facial / gaze measurement"
                "P3" -> "Bilateral auditory stimulation"
                "P4" -> "Embodied / AR"
                "P5" -> "Muse / EEG"
                else -> "Unknown research build"
            },
            facialGazeEnabled = BuildConfig.FACIAL_GAZE_ENABLED,
            bilateralAudioEnabled = BuildConfig.BILATERAL_AUDIO_ENABLED,
            embodiedArEnabled = BuildConfig.EMBODIED_AR_ENABLED,
            eegEnabled = BuildConfig.EEG_ENABLED,
        )
    }
}
